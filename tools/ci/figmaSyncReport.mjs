import { createHash } from 'node:crypto';
import { readFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';

/**
 * Renders the report written by `sync-icons` and `sync-illustrations` (see `SyncReport` in
 * packages/icons/scripts/sync-icons/syncReport.ts) for the sync-figma-assets workflow: the pull
 * request description, the Slack message for designers, and the fingerprint used to announce each
 * set of problems only once.
 */

/** Asset names and messages come from Figma, so keep them from breaking out of their formatting. */
const plain = (text) =>
  String(text)
    .replace(/[`\r\n]+/g, ' ')
    .trim();

const escapeSlack = (text) =>
  plain(text).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

const countSummary = ({ added, updated, renamed, deleted }) =>
  [
    ['added', added],
    ['updated', updated],
    ['renamed', renamed],
    ['deleted', deleted],
  ]
    .filter(([, count]) => count > 0)
    .map(([label, count]) => `${count} ${label}`)
    .join(', ') || 'no asset changes';

/** The rejected assets as a markdown list, for the pull request and the job summary. */
export const renderRejections = (report) =>
  report.rejected
    .map(({ name, message, url }) => `- \`${plain(name)}\`: ${plain(message)} ([Figma](${url}))`)
    .join('\n');

export const renderPullRequestBody = (report) => {
  const sections = [
    '## What changed? Why?',
    `Automated ${report.target} sync from Figma: ${countSummary(report.counts)}. Generated by the Sync Figma Assets workflow; review it like any other PR.`,
  ];

  if (report.breaking) {
    sections.push(
      '**Breaking changes:** assets were renamed or deleted. This needs a major version bump, a migration guide and a migrator script (see the version plan in this PR).',
    );
  }

  if (report.rejected.length > 0) {
    sections.push(
      `### Skipped, needs a fix in Figma\n\nThese were not synced. Designers have been notified, and they are picked up again on the next sync once fixed.\n\n${renderRejections(report)}`,
    );
  }

  sections.push(
    '## Testing',
    '### Testing instructions\n\nReview the generated assets and the visreg run on this PR. Nothing is merged automatically.',
    '## Illustrations/Icons Checklist',
    [
      '- [ ] verified visreg changes with Terran (include link to visreg run/approval)',
      '- [ ] all illustration/icons names have been reviewed by Dom and/or Terran',
    ].join('\n'),
    '## Change management',
    ['type=routine', 'risk=low', 'impact=sev5', '', 'automerge=false'].join('\n'),
  );

  return `${sections.join('\n\n')}\n`;
};

/** The Slack message that tells designers which assets to fix. */
export const renderSlackPayload = (report, { runUrl } = {}) => {
  const count = report.rejected.length;
  const lines = report.rejected.map(
    ({ name, message, url }) =>
      `• \`${plain(name)}\`: ${escapeSlack(message)} (<${url}|Open in Figma>)`,
  );
  const footer = [
    'Fix them in Figma and publish the library; the next sync picks them up.',
    runUrl ? `<${runUrl}|Sync run>` : undefined,
  ]
    .filter(Boolean)
    .join(' ');
  return {
    text: [
      `:warning: The ${report.target} sync skipped ${count} ${count === 1 ? 'asset' : 'assets'}. ${count === 1 ? 'It needs' : 'They need'} a fix in Figma:`,
      ...lines,
      footer,
    ].join('\n'),
  };
};

/** Identical for the same assets and problems, so unchanged problems are announced only once. */
export const rejectionFingerprint = (report) => {
  const entries = report.rejected.map(({ name, message }) => `${name}\t${message}`).sort();
  return createHash('sha256').update(entries.join('\n')).digest('hex').slice(0, 16);
};

const commands = {
  'pr-body': (report) => renderPullRequestBody(report),
  rejections: (report) => `${renderRejections(report)}\n`,
  slack: (report, options) => JSON.stringify(renderSlackPayload(report, options)),
  fingerprint: (report) => `${rejectionFingerprint(report)}\n`,
};

const main = () => {
  const [command, reportPath, ...rest] = process.argv.slice(2);
  const render = commands[command];
  if (!render || !reportPath) {
    console.error(
      `Usage: figmaSyncReport.mjs <${Object.keys(commands).join('|')}> <report.json> [--run-url <url>]`,
    );
    process.exit(1);
  }
  const runUrlIndex = rest.indexOf('--run-url');
  const runUrl = runUrlIndex >= 0 ? rest[runUrlIndex + 1] : undefined;
  process.stdout.write(render(JSON.parse(readFileSync(reportPath, 'utf-8')), { runUrl }));
};

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) main();
