import path from 'node:path';

import { profile } from '../profile';
import { codegenHeader, resolveSvgPath, toSingleQuotedLiteral } from '../sinks/files';

describe('resolveSvgPath', () => {
  const out = '/repo/packages/icons/src/svgs';

  it('resolves names inside the output dir', () => {
    expect(resolveSvgPath(out, 'add-24-active')).toBe(path.join(out, 'add-24-active.svg'));
  });

  it('returns undefined for names that escape the output dir', () => {
    expect(resolveSvgPath(out, '../../../etc/passwd')).toBeUndefined();
  });
});

describe('codegenHeader', () => {
  it('names the script of the package that generated the file', () => {
    expect(codegenHeader).toContain(`generated by the ${profile.scriptName} script`);
  });
});

describe('toSingleQuotedLiteral', () => {
  const readBack = (value: unknown) => new Function(`return ${toSingleQuotedLiteral(value)}`)();

  it('writes strings in single quotes, like the generated files', () => {
    expect(toSingleQuotedLiteral({ add: ['plus', 'new'] })).toBe(
      "{\n  'add': [\n    'plus',\n    'new'\n  ]\n}",
    );
  });

  it.each([
    ["x': []}; process.exit(1); const rest = {'y"],
    ["it's"],
    ['say "hi"'],
    ['back\\slash'],
    ['ends with a backslash\\'],
    ['a\\"b'],
    ["quote then backslash '\\"],
    ['two\nlines'],
    ['</script>'],
    ['\uf0001 private use'],
  ])('reads back %j as the same text, so nothing in it can become code', (text) => {
    const original = { [text]: [text] };
    expect(readBack(original)).toEqual(original);
  });

  it('lays values out like JSON.stringify, with single quotes', () => {
    const value = {
      a: ['x', 'y'],
      b: {},
      c: [],
      d: { e: 'f' },
      g: 1,
      h: true,
      i: null,
      j: undefined,
    };
    expect(toSingleQuotedLiteral(value)).toBe(JSON.stringify(value, null, 2).replace(/"/g, "'"));
  });

  it('does not run text that tries to end the string', () => {
    const exit = jest.spyOn(process, 'exit').mockImplementation((() => undefined) as never);
    readBack({ description: ["x'); process.exit(1); ('"] });
    expect(exit).not.toHaveBeenCalled();
    exit.mockRestore();
  });
});
